#!/usr/bin/env python3
"""Generate an OpenMX <MD.Init.Velocity block with Maxwell-Boltzmann velocities.

The velocities (m/s) are drawn for a target temperature, the centre-of-mass
momentum is removed, and the set is rescaled so that
    T = 2 * Ukc / (3 * N * kB)
which is the definition OpenMX uses for the instantaneous temperature.

Usage:
    python3 gen_init_velocity.py H2O_NVE.dat --temp 300 --seed 1 >> H2O_NVE.dat
    python3 gen_init_velocity.py Si64_NVT_NH.dat --temp 1000 --fix 1,2

Only numpy is required. Atomic masses are taken from the 4th column of
<Definition.of.Atomic.Species if present, otherwise from a built-in table
(standard atomic weights; OpenMX's own internal values may differ slightly,
which does not matter because the velocities are rescaled to the target T).
"""
import argparse
import re
import sys

import numpy as np

KB = 1.380649e-23          # J/K
AMU = 1.66053906660e-27    # kg

MASS = {
    "H": 1.008, "He": 4.0026, "Li": 6.94, "Be": 9.0122, "B": 10.81, "C": 12.011,
    "N": 14.007, "O": 15.999, "F": 18.998, "Ne": 20.180, "Na": 22.990, "Mg": 24.305,
    "Al": 26.982, "Si": 28.085, "P": 30.974, "S": 32.06, "Cl": 35.45, "Ar": 39.948,
    "K": 39.098, "Ca": 40.078, "Sc": 44.956, "Ti": 47.867, "V": 50.942, "Cr": 51.996,
    "Mn": 54.938, "Fe": 55.845, "Co": 58.933, "Ni": 58.693, "Cu": 63.546, "Zn": 65.38,
    "Ga": 69.723, "Ge": 72.630, "As": 74.922, "Se": 78.971, "Br": 79.904, "Kr": 83.798,
    "Rb": 85.468, "Sr": 87.62, "Y": 88.906, "Zr": 91.224, "Nb": 92.906, "Mo": 95.95,
    "Ru": 101.07, "Rh": 102.91, "Pd": 106.42, "Ag": 107.87, "Cd": 112.41, "In": 114.82,
    "Sn": 118.71, "Sb": 121.76, "Te": 127.60, "I": 126.90, "Xe": 131.29, "Cs": 132.91,
    "Ba": 137.33, "La": 138.91, "Hf": 178.49, "Ta": 180.95, "W": 183.84, "Re": 186.21,
    "Os": 190.23, "Ir": 192.22, "Pt": 195.08, "Au": 196.97, "Hg": 200.59, "Tl": 204.38,
    "Pb": 207.2, "Bi": 208.98,
}


def strip_comment(line):
    return line.split("#", 1)[0].strip()


def read_block(lines, name):
    """Return the stripped lines between <name and name> (case-insensitive)."""
    out, inside = [], False
    for raw in lines:
        line = strip_comment(raw)
        low = line.lower()
        if low.startswith("<" + name.lower()):
            inside = True
            continue
        if inside and low.startswith(name.lower() + ">"):
            return out
        if inside and line:
            out.append(line)
    if inside:
        sys.exit("ERROR: block <%s is not closed" % name)
    return out


def element_of(species, pao):
    """Guess the element from the PAO name (e.g. Fe5.5H-s3p2d1 -> Fe)."""
    for token in (pao, species):
        m = re.match(r"([A-Z][a-z]?)", token)
        if m and m.group(1) in MASS:
            return m.group(1)
    sys.exit("ERROR: cannot determine element of species %s (%s)" % (species, pao))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("datfile", help="OpenMX input file (.dat)")
    ap.add_argument("--temp", type=float, required=True, help="target temperature in K")
    ap.add_argument("--seed", type=int, default=None, help="random seed")
    ap.add_argument("--fix", default="", help="comma separated atom indices with zero velocity")
    args = ap.parse_args()

    with open(args.datfile) as f:
        lines = f.readlines()

    masses_by_species = {}
    for line in read_block(lines, "Definition.of.Atomic.Species"):
        p = line.split()
        if len(p) < 3:
            continue
        if len(p) >= 4:
            masses_by_species[p[0]] = float(p[3])
        else:
            masses_by_species[p[0]] = MASS[element_of(p[0], p[1])]

    atoms = read_block(lines, "Atoms.SpeciesAndCoordinates")
    if not atoms:
        sys.exit("ERROR: <Atoms.SpeciesAndCoordinates block not found")
    idx = [int(a.split()[0]) for a in atoms]
    mass = np.array([masses_by_species[a.split()[1]] for a in atoms]) * AMU
    n = len(atoms)

    fixed = {int(x) for x in args.fix.split(",") if x.strip()}
    free = np.array([i not in fixed for i in idx])
    if free.sum() < 2:
        sys.exit("ERROR: need at least two free atoms")

    rng = np.random.default_rng(args.seed)
    sigma = np.sqrt(KB * args.temp / mass)               # m/s, per Cartesian component
    v = rng.normal(size=(n, 3)) * sigma[:, None]
    v[~free] = 0.0

    # remove centre-of-mass momentum of the free atoms
    p_com = (mass[free, None] * v[free]).sum(axis=0) / mass[free].sum()
    v[free] -= p_com

    # rescale exactly to the target temperature (OpenMX: 3N degrees of freedom)
    ukc = 0.5 * np.sum(mass[:, None] * v ** 2)
    t_now = 2.0 * ukc / (3.0 * n * KB)
    if t_now > 0.0:
        v *= np.sqrt(args.temp / t_now)

    print("# generated by gen_init_velocity.py: T = %.1f K, seed = %s, unit = m/s"
          % (args.temp, args.seed))
    print("<MD.Init.Velocity")
    for i, vi in zip(idx, v):
        print("  %4d  %14.4f  %14.4f  %14.4f" % (i, vi[0], vi[1], vi[2]))
    print("MD.Init.Velocity>")


if __name__ == "__main__":
    main()
