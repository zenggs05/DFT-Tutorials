#!/usr/bin/env python3
"""Write an OpenMX 4.0 input for an n x n x n diamond-Si supercell (8 n^3 atoms).

Used to produce bigger versions of the inputs in this directory, e.g.

    python3 make_si_supercell.py 8 --solver DC-LNO --rcut 8.0 -o Si4096_DC-LNO.dat
    python3 make_si_supercell.py 3 --solver Band --kgrid 2 2 2 -o Si216_Band.dat
    python3 make_si_supercell.py 4 --solver Krylov --rattle 0.03 -o Si512_Krylov_rattled.dat

Only the Python standard library is needed.  The structure is ideal unless --rattle is
given (random Gaussian displacements in Angstrom, reproducible with --seed).
"""
import argparse
import itertools
import random

BASIS = [(0.0, 0.0, 0.0), (0.0, 0.5, 0.5), (0.5, 0.0, 0.5), (0.5, 0.5, 0.0),
         (0.25, 0.25, 0.25), (0.25, 0.75, 0.75), (0.75, 0.25, 0.75), (0.75, 0.75, 0.25)]

SOLVER_LINES = {
    "Band": ["scf.EigenvalueSolver        Band",
             "scf.Kgrid                   {k1} {k2} {k3}"],
    "Cluster": ["scf.EigenvalueSolver        Cluster"],
    "DC": ["scf.EigenvalueSolver        DC",
           "orderN.HoppingRanges        {rcut}        # Ang"],
    "DC-LNO": ["scf.EigenvalueSolver        DC-LNO",
               "orderN.HoppingRanges        {rcut}        # Ang",
               "orderN.LNO.Buffer           0.2",
               "orderN.LNO.Occ.Cutoff       0.1",
               "scf.dclno.threading         on"],
    "Krylov": ["scf.EigenvalueSolver        Krylov",
               "orderN.HoppingRanges        {rcut}        # Ang",
               "orderN.KrylovH.order        {korder}"],
}


def build(args):
    n = args.n
    cell = args.a * n
    rng = random.Random(args.seed)
    coords = []
    for i, j, k in itertools.product(range(n), repeat=3):
        for b in BASIS:
            f = [(b[0] + i) / n, (b[1] + j) / n, (b[2] + k) / n]
            if args.rattle > 0.0:
                f = [x + rng.gauss(0.0, args.rattle) / cell for x in f]
            coords.append([x % 1.0 for x in f])
    name = args.name or "si{}_{}".format(len(coords), args.solver.lower().replace("-", ""))
    lines = [
        "# Si{} ({}x{}x{} conventional diamond supercell, a = {} A), generated by make_si_supercell.py".format(
            len(coords), n, n, n, args.a),
        "# solver = {}. OpenMX 4.0.".format(args.solver),
        "",
        "System.CurrrentDirectory    ./",
        "System.Name                 {}".format(name),
        "DATA.PATH                   {}   # dir containing PAO/ and VPS/".format(args.data_path),
        "level.of.stdout             1",
        "level.of.fileout            0",
        "",
        "Species.Number              1",
        "<Definition.of.Atomic.Species",
        "  Si   {}   Si_PBE19".format(args.basis),
        "Definition.of.Atomic.Species>",
        "",
        "Atoms.Number                {}".format(len(coords)),
        "Atoms.SpeciesAndCoordinates.Unit   FRAC",
        "<Atoms.SpeciesAndCoordinates",
    ]
    for idx, f in enumerate(coords, 1):
        lines.append("  {:5d}  Si  {:.6f}  {:.6f}  {:.6f}   2.0 2.0".format(idx, *f))
    lines += [
        "Atoms.SpeciesAndCoordinates>",
        "",
        "Atoms.UnitVectors.Unit      Ang",
        "<Atoms.UnitVectors",
        "  {:.4f}   0.0000   0.0000".format(cell),
        "   0.0000  {:.4f}   0.0000".format(cell),
        "   0.0000   0.0000  {:.4f}".format(cell),
        "Atoms.UnitVectors>",
        "",
        "scf.XcType                  GGA-PBE",
        "scf.SpinPolarization        off",
        "scf.ElectronicTemperature   300.0",
        "scf.energycutoff            {}".format(args.ecut),
        "scf.maxIter                 100",
    ]
    k1, k2, k3 = args.kgrid
    for tmpl in SOLVER_LINES[args.solver]:
        lines.append(tmpl.format(k1=k1, k2=k2, k3=k3, rcut=args.rcut, korder=args.korder))
    lines += [
        "scf.Mixing.Type             RMM-DIISK",
        "scf.Init.Mixing.Weight      0.05",
        "scf.Min.Mixing.Weight       0.001",
        "scf.Max.Mixing.Weight       0.20",
        "scf.Mixing.History          15",
        "scf.Mixing.StartPulay       8",
        "scf.criterion               1.0e-8",
        "",
        "MD.Type                     Nomd",
        "",
    ]
    return "\n".join(lines)


def main():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("n", type=int, help="supercell size: n x n x n conventional cells (8 n^3 atoms)")
    p.add_argument("--solver", choices=sorted(SOLVER_LINES), default="DC-LNO")
    p.add_argument("--rcut", type=float, default=8.0, help="orderN.HoppingRanges in Ang (O(N) solvers)")
    p.add_argument("--korder", type=int, default=400, help="orderN.KrylovH.order (Krylov)")
    p.add_argument("--kgrid", type=int, nargs=3, default=(1, 1, 1), help="scf.Kgrid (Band)")
    p.add_argument("--a", type=float, default=5.43, help="cubic lattice constant in Ang")
    p.add_argument("--basis", default="Si7.0-s2p1d1", help="PAO basis (Quick: Si7.0-s2p1d1, Standard: Si7.0-s2p2d1)")
    p.add_argument("--ecut", type=float, default=200.0, help="scf.energycutoff in Ry")
    p.add_argument("--rattle", type=float, default=0.0, help="Gaussian displacement sigma in Ang")
    p.add_argument("--seed", type=int, default=1)
    p.add_argument("--name", default=None, help="System.Name (default derived from size and solver)")
    p.add_argument("--data-path", default="/opt/openmx4.0/DFT_DATA19")
    p.add_argument("-o", "--output", required=True, help="output .dat file")
    args = p.parse_args()
    if args.n < 1:
        p.error("n must be >= 1")
    with open(args.output, "w", newline="\n") as fh:
        fh.write(build(args))
    print("wrote", args.output)


if __name__ == "__main__":
    main()
