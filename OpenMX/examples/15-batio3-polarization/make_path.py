#!/usr/bin/env python3
"""Build lambda-path inputs between a centrosymmetric and a polar structure.

Reads two OpenMX inputs that share the same cell and atom order and use
Atoms.SpeciesAndCoordinates.Unit FRAC, linearly interpolates the fractional
coordinates (minimum image, so 0.975 vs 0.000 is a shift of -0.025) and writes
one input per lambda with System.Name set to <prefix>_lam<lambda>.

Optionally, the polar end point is taken from the block
"Fractional coordinates of the final structure" of a relaxation .out file.

Example:
    python3 make_path.py BaTiO3_cubic_ref.dat BaTiO3_tetra_polB.dat \
        --lambdas 0 0.25 0.5 0.75 1.0 --from-out bto_relax.out
"""
import argparse
import sys


def read_lines(path):
    with open(path) as fh:
        return fh.read().splitlines()


def coord_block(lines):
    """Return (start, end) line indices of the coordinate rows; check FRAC."""
    unit = None
    start = end = None
    for i, line in enumerate(lines):
        low = line.strip().lower()
        if low.startswith("atoms.speciesandcoordinates.unit"):
            unit = low.split()[1]
        if low.startswith("<atoms.speciesandcoordinates"):
            start = i + 1
        if low.startswith("atoms.speciesandcoordinates>"):
            end = i
    if start is None or end is None:
        sys.exit("coordinate block not found")
    if unit != "frac":
        sys.exit("this script expects Atoms.SpeciesAndCoordinates.Unit FRAC")
    return start, end


def parse_rows(lines, start, end):
    rows = []
    for line in lines[start:end]:
        f = line.split()
        if len(f) < 5:
            continue
        rows.append((f[0], f[1], [float(x) for x in f[2:5]], f[5:]))
    return rows


def final_frac_from_out(path, natom):
    lines = read_lines(path)
    for i, line in enumerate(lines):
        if "Fractional coordinates of the final structure" in line:
            coords = []
            for l2 in lines[i + 1:]:
                f = l2.split()
                if len(f) >= 5 and f[0].isdigit():
                    coords.append([float(x) for x in f[2:5]])
                    if len(coords) == natom:
                        return coords
            break
    sys.exit(f"{path}: block 'Fractional coordinates of the final structure' not found")


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("start", help="lambda = 0 input (centrosymmetric)")
    ap.add_argument("end", help="lambda = 1 input (polar)")
    ap.add_argument("--lambdas", nargs="+", type=float,
                    default=[0.0, 0.25, 0.5, 0.75, 1.0])
    ap.add_argument("--from-out", help="relaxation .out: use its final fractional "
                    "coordinates for the lambda = 1 end point")
    ap.add_argument("--prefix", default="bto", help="System.Name prefix")
    ap.add_argument("--file-prefix", default="BaTiO3", help="output file prefix")
    args = ap.parse_args()

    l0, l1 = read_lines(args.start), read_lines(args.end)
    s0, e0 = coord_block(l0)
    s1, e1 = coord_block(l1)
    r0, r1 = parse_rows(l0, s0, e0), parse_rows(l1, s1, e1)
    if len(r0) != len(r1) or any(a[1] != b[1] for a, b in zip(r0, r1)):
        sys.exit("the two inputs must have the same atoms in the same order")
    end_xyz = [r[2] for r in r1]
    if args.from_out:
        end_xyz = final_frac_from_out(args.from_out, len(r1))

    for lam in args.lambdas:
        tag = f"{lam:.2f}"
        name = f"{args.prefix}_lam{tag}"
        rows = []
        for (idx, sp, x0, rest), x1 in zip(r0, end_xyz):
            x = []
            for a, b in zip(x0, x1):
                d = b - a
                d -= round(d)                  # minimum image in fractional units
                x.append((a + lam * d) % 1.0)
            rows.append(f"  {idx}  {sp:<3s} " + " ".join(f"{v:10.6f}" for v in x)
                        + "    " + "  ".join(rest))
        out = [f"# Generated by make_path.py: lambda = {tag} "
               f"(0 = {args.start}, 1 = polar end point); header below is copied"]
        for i, line in enumerate(l0):
            if s0 <= i < e0:
                if i == s0:
                    out.extend(rows)
                continue
            if line.strip().lower().startswith("system.name"):
                out.append(f"System.Name                 {name}")
                continue
            out.append(line)
        fname = f"{args.file_prefix}_lam{tag}.dat"
        with open(fname, "w", newline="\n") as fh:
            fh.write("\n".join(out) + "\n")
        print(f"wrote {fname}  (System.Name {name})")


if __name__ == "__main__":
    main()
